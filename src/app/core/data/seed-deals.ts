export const SEED_DEALS: readonly Readonly<Deal>[] = SEED_ROWS.map(toDeal);

export function createSeedDeals(): Deal[] {
  return SEED_DEALS.map((deal) => ({ ...deal }));
}

function toDeal(row: SeedRow, index: number): Deal {
  const [
    account,
    title,
    owner,
    region,
    stage,
    listValue,
    discountPct,
    probability,
    closeDate,
    lastActivityDays,
  ] = row;
  return {
    id: `D-${1001 + index}`,
    account,
    title,
    owner,
    region,
    stage,
    listValue,
    discountPct,
    probability,
    closeDate,
    contractStatus: stage === 'closed-won' ? 'active' : 'none',
    contactEmail: `procurement@${slugify(account)}.example`,
    lastActivityDays,
  };
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}
